# 1. 海量抓取商品有两种方式：搜索页抓取或店铺页抓取，这两种抓取不太容易被封，且都会更新commodity_info, shop_info, commodity_sales表,
#    这两种抓取方式都不会更新商品详细信息，仅更新商品ID、标题、链接等基本信息；
# 2. 商品销售信息的更新方式有一种：通过店铺页指定商品列表抓取，这种抓取也不太容易被封，会更新shop_info, commodity_sales表,
# 3. 商品细节的抓取方式有一种：即商品页面抓取，这很容易被封，会更新commodity_info表；
# 4. 参考 #1、#2 和 #3，有三种抓取任务，分别为search_crawl_task, shop_crawl_task, detail_crawl_task,
#    这几种抓取任务由此脚本分析并生成；
# 5. 分析的基本逻辑：
#    a. 基于已有信息，某些商品的销售信息在当前时间点看没有更新价值，什么也不做；
#    b. 若商品销售信息显示其有更新价值，视情况应保持一个最低的更新频率，比如一周/一月，若某商品的销售信息超时未更新，应建立shop_crawl_task任务；
#    c. 有更新价值的商品的商品细节也应保持一个最低的更新频率，比如两周，我们每天更新一点，因为这很容易被封；
#    d. 有更新价值的商铺也应保持一个最低的更新频率，比如一周，若商铺内容超时未更新，应建立shop_crawl_task任务；
#    e. 满足某些特殊条件的商品，不但应被更新销售信息和商品信息，也应该抓取所有商品页面素材并存放于本地，便于之后分析和上架；
# 目前使用的策略如下（请同步保持更新）：
# 1. search_crawl_task 添加的具体策略：
#    a. 手动提供搜索词，调用程序添加任务到search_crawl_tasks表，这主要是出于启发式的增加商品和销售信息的目的；
#    b. 同样的搜索词可以在不同时间反复运行，这同时是为了增加商品和销售信息；
# 2. shop_crawl_task 添加的具体策略：
#    a. 可以手动提供目标商铺，调用程序添加任务到shop_crawl_task表，这同样是出于启发式的增加商品和销售信息的目的；
#    b. 同样的店铺可以在不同时间反复抓取，这同时是为了增加商品和销售信息；
#    c. 若基于现有数据，某商铺的基础年销售量超过10000元，且商铺内容一周内未更新，则添加任务到shop_crawl_task表；
# 3. detail_crawl_task 添加的具体策略：
#    a. 若某商品的基础年销售额超过1000元，且商品信息一周内未被detail_crawl_task更新，则建立detail_crawl_task任务；
#    b. 在商品详情页面被抓取的同时，下载页面素材到本地
